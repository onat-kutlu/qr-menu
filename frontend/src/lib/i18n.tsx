const LocaleContext = createContext<LocaleContextValue | null>(null);

export function LocaleProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(() => (localStorage.getItem('qr-menu-locale') as Locale) || 'en');
  const setLocale = (next: Locale) => { localStorage.setItem('qr-menu-locale', next); setLocaleState(next); };
  const value = useMemo(() => ({ locale, setLocale, t: (key: string) => translations[locale][key] || key }), [locale]);
  return <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>;
}

export function useLocale() {
  const value = useContext(LocaleContext);
  if (!value) throw new Error('useLocale must be used inside LocaleProvider');
  return value;
}

export function LanguageSwitcher() {
  const { locale, setLocale, t } = useLocale();
  return <button type="button" onClick={() => setLocale(locale === 'en' ? 'tr' : 'en')} className="rounded-lg border border-slate-700 px-3 py-2 text-xs font-semibold text-slate-300 hover:border-cyan-300 hover:text-cyan-200" aria-label={t('common.changeLanguage')}>{locale === 'en' ? 'TR' : 'EN'}</button>;
}

export function getRoleLabel(role: string | undefined, translate: (key: string) => string) {
  return role ? translate(`role.${role}`) : '-';
}

export function getStatusLabel(status: string | undefined, translate: (key: string) => string) {
  return status ? translate(`status.${status}`) : '-';
}
